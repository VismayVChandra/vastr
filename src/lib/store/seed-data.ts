export function buildSeedWardrobe(userId: string): WardrobeItem[] {
  return SEED_ITEMS.map((item) => ({
    ...item,
    id: uid(),
    userId,
    favorite: item.favorite ?? false,
    archived: false,
    createdAt: daysAgo(60),
    updatedAt: daysAgo(1),
  }));
}

